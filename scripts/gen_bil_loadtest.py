#!/usr/bin/env python3
"""
Generate the IDFC BIL (Business Instant Loan) load test: N copies of the
happy-path eligibility scenario plus three ramp campaigns (20, 50, 100) so we
can step the load up.

The campaign loader dedupes scenario PATHS, so N concurrent calls of the same
persona need N distinct files (each a copy with a unique `name:`). We generate
100 copies once, and each ramp campaign references the first 20 / 50 / 100.

Usage (from repo root, judge_it/):
    python scripts/gen_bil_loadtest.py            # 100 copies + 20/50/100 ramps

Then run a ramp step (START AT 1 to validate, then step up):
    judge_it campaign clients/idfc/bil/load-test/.generated/bil-020.yaml -m 1
    judge_it campaign clients/idfc/bil/load-test/.generated/bil-020.yaml -m 20
    judge_it campaign clients/idfc/bil/load-test/.generated/bil-050.yaml -m 50
    judge_it campaign clients/idfc/bil/load-test/.generated/bil-100.yaml -m 100

NOTE: every run places REAL outbound Twilio calls to +918062123180. Ramp up
deliberately (1 -> 20 -> 50 -> 100) and watch the per-call logs under logs/.
"""
import re
import sys
from pathlib import Path

# Max copies to materialise; the ramp steps below must all be <= this.
POOL = int(sys.argv[1]) if len(sys.argv) > 1 else 200
RAMPS = [20, 50, 100, 200]

BASE = Path("clients/idfc/bil")
SRC = BASE / "happy-path-eligibility.yaml"
OUT_DIR = BASE / "load-test" / ".generated"
SCEN_DIR = OUT_DIR / "scenarios"


def stamp_name(text: str, tag: str) -> str:
    """Append a unique suffix to the scenario's `name:` so copies are
    distinguishable in logs/results (path is what the loader dedupes on)."""
    return re.sub(
        r'^name: "(.*)"$',
        lambda m: f'name: "{m.group(1)} · {tag}"',
        text,
        count=1,
        flags=re.M,
    )


def ramp_campaign(n: int) -> str:
    entries = "\n".join(f"  - scenarios/bil-{i:03d}.yaml" for i in range(1, n + 1))
    return f"""# =============================================================================
# AUTO-GENERATED by scripts/gen_bil_loadtest.py — DO NOT hand-edit.
# IDFC · Avni · BIL · LOAD ramp step: {n} concurrent calls
# =============================================================================
# {n} copies of the same qualified happy-path eligibility persona against the
# BIL bot (agent 400, +918062123180). {n} distinct files are required because
# the loader dedupes scenario paths.
#
# START AT 1 to validate the flow end-to-end, THEN run at {n}:
#   judge_it campaign {OUT_DIR}/bil-{n:03d}.yaml -m 1
#   judge_it campaign {OUT_DIR}/bil-{n:03d}.yaml -m {n}
#
# Every run places REAL outbound calls to +918062123180. Latency/capacity is
# read from the per-call logs under logs/.
#
# Regenerate:  python scripts/gen_bil_loadtest.py
# =============================================================================

name: "IDFC · Avni · BIL · LOAD ramp {n}"
description: |
  {n} concurrent qualified happy-path eligibility calls against the IDFC BIL
  bot (agent 400, +918062123180), for capacity/latency testing. Same persona
  across all copies. Read latency from the per-call logs under logs/.

max_concurrency: {n}

fail_fast: false

scenarios:
{entries}
"""


def main() -> None:
    if max(RAMPS) > POOL:
        raise SystemExit(f"POOL ({POOL}) must be >= largest ramp ({max(RAMPS)})")

    src = SRC.read_text()
    SCEN_DIR.mkdir(parents=True, exist_ok=True)

    # clear any previous generation so counts stay exact
    for old in SCEN_DIR.glob("*.yaml"):
        old.unlink()
    for old in OUT_DIR.glob("bil-*.yaml"):
        old.unlink()

    for i in range(1, POOL + 1):
        (SCEN_DIR / f"bil-{i:03d}.yaml").write_text(stamp_name(src, f"load {i:03d}"))

    for n in RAMPS:
        (OUT_DIR / f"bil-{n:03d}.yaml").write_text(ramp_campaign(n))

    print(f"Generated {POOL} scenarios in {SCEN_DIR}")
    print(f"Ramp campaigns: " + ", ".join(f"bil-{n:03d}.yaml" for n in RAMPS))


if __name__ == "__main__":
    main()
