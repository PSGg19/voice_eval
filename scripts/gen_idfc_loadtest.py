#!/usr/bin/env python3
"""
Generate the IDFC Avni load-test: N Gemini + N Qwen copies of the happy-path
latency scenario, interleaved (gemini-001, qwen-001, gemini-002, qwen-002, ...)
into one campaign so a one-by-one worker pool spreads load evenly across both
bots.

The campaign loader dedupes scenario paths, so we need N distinct files per
model (copies of the two base scenarios, with a unique `name:` per copy).

Usage (from repo root, judge_it/):
    python scripts/gen_idfc_loadtest.py            # default N=100 per model
    python scripts/gen_idfc_loadtest.py 50         # N=50 per model (100 total)
"""
import re
import sys
from pathlib import Path

N = int(sys.argv[1]) if len(sys.argv) > 1 else 100

BASE = Path("clients/idfc/unsecured-cc")
GEM_SRC = BASE / "gemini-test" / "happy-path-latency.yaml"
QWN_SRC = BASE / "qwen-test" / "happy-path-latency.yaml"
OUT_DIR = BASE / "load-test" / ".generated"
CAMPAIGN = BASE / "load-test" / "load-interleaved.yaml"


def stamp_name(text: str, tag: str) -> str:
    """Append a unique suffix to the scenario's `name:` so copies are
    distinguishable in logs/results (path is what the loader dedupes on)."""
    return re.sub(
        r'^name: "(.*)"$',
        lambda m: f'name: "{m.group(1)} · {tag}"',
        text,
        count=1,
        flags=re.M,
    )


def main() -> None:
    gem = GEM_SRC.read_text()
    qwn = QWN_SRC.read_text()
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # clear any previous generation so counts stay exact
    for old in OUT_DIR.glob("*.yaml"):
        old.unlink()

    lines: list[str] = []
    for i in range(1, N + 1):
        gi, qi = f"gemini-{i:03d}", f"qwen-{i:03d}"
        (OUT_DIR / f"{gi}.yaml").write_text(stamp_name(gem, f"load {i:03d}"))
        (OUT_DIR / f"{qi}.yaml").write_text(stamp_name(qwn, f"load {i:03d}"))
        # interleave: gemini then qwen, per index
        lines.append(f"  - .generated/{gi}.yaml")
        lines.append(f"  - .generated/{qi}.yaml")

    campaign = f"""# =============================================================================
# AUTO-GENERATED by scripts/gen_idfc_loadtest.py — DO NOT hand-edit.
# IDFC · Avni · LOAD test · Gemini vs Qwen ({N}+{N} interleaved = {2 * N} calls)
# =============================================================================
# {N} Gemini (agent 423) + {N} Qwen (agent 420) copies of the same happy-path
# latency scenario, interleaved (gemini-001, qwen-001, gemini-002, ...) so a
# one-by-one worker pool spreads load evenly across both bots.
#
# max_concurrency is capped at 50 in YAML; override on the CLI to fire more:
#   judge_it campaign {CAMPAIGN} -m {2 * N}     # {N} Gemini + {N} Qwen all concurrent
#   judge_it campaign {CAMPAIGN} -m {N}         # {N} in flight at a time, alternating
#
# Regenerate / change counts:  python scripts/gen_idfc_loadtest.py <N>
# =============================================================================

name: "IDFC · Avni · LOAD · Gemini vs Qwen ({N}+{N} interleaved)"
description: |
  Load test: {N} concurrent calls to the Gemini bot (agent 423) and {N} to the
  Qwen bot (agent 420), same happy-path persona, interleaved so load is even.
  Latency/capacity read from the per-call logs under logs/.

max_concurrency: 50

fail_fast: false

scenarios:
{chr(10).join(lines)}
"""
    CAMPAIGN.write_text(campaign)
    print(f"Generated {2 * N} scenarios in {OUT_DIR}")
    print(f"Campaign: {CAMPAIGN}")


if __name__ == "__main__":
    main()
