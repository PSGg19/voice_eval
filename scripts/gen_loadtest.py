#!/usr/bin/env python3
"""Generate V2 load-test artifacts for a concurrency ramp.

The campaign loader dedupes scenario paths, so running the *same* V2
persona N times requires N distinct files. This script stamps out N
copies of a base scenario and writes one campaign per ramp step that
lists exactly the first K copies — so each campaign launches exactly K
concurrent V2 calls.

Usage:
    python scripts/gen_loadtest.py \
        --base clients/load-test/scenarios/simple/small-talk.yaml \
        --steps 25,50,75,100

Then run (start small!):
    opkura campaign clients/load-test/.generated/load-025.yaml -m 25
    opkura campaign clients/load-test/.generated/load-050.yaml -m 50
    opkura campaign clients/load-test/.generated/load-075.yaml -m 75
    opkura campaign clients/load-test/.generated/load-100.yaml -m 100

Each call is a real outbound call. The whole .generated/ tree is
gitignored.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--base",
        default="clients/load-test/scenarios/simple/small-talk.yaml",
        help="Base V2 scenario to replicate.",
    )
    ap.add_argument(
        "--steps",
        default="25,50,75,100",
        help="Comma-separated ramp steps (concurrent-call counts).",
    )
    ap.add_argument(
        "--out",
        default="clients/load-test/.generated",
        help="Output dir for copies + ramp campaigns (gitignored).",
    )
    args = ap.parse_args()

    base = Path(args.base)
    if not base.exists():
        raise SystemExit(f"base scenario not found: {base}")
    steps = [int(s) for s in args.steps.split(",") if s.strip()]
    if not steps:
        raise SystemExit("no ramp steps given")
    total = max(steps)

    out = Path(args.out)
    scen_dir = out / "scenarios"
    scen_dir.mkdir(parents=True, exist_ok=True)

    base_text = base.read_text(encoding="utf-8")

    # Stamp out `total` copies. We tweak the `name:` line so each call
    # gets a distinct label in the campaign report; everything else
    # (target, persona, evaluation) is identical.
    copy_paths: list[Path] = []
    for i in range(1, total + 1):
        text = base_text
        tag = f"  [load #{i:03d}]"
        # Append the tag to the scenario name for per-call traceability.
        lines = text.splitlines()
        for idx, line in enumerate(lines):
            if line.startswith("name:"):
                lines[idx] = line.rstrip().rstrip('"') + tag + '"'
                break
        text = "\n".join(lines) + "\n"
        p = scen_dir / f"small-talk-{i:03d}.yaml"
        p.write_text(text, encoding="utf-8")
        copy_paths.append(p)

    print(f"Generated {total} scenario copies in {scen_dir}/")

    # One campaign per ramp step. YAML max_concurrency stays <= 50 (the
    # loader caps it); the actual concurrency is set on the CLI with
    # `-m K`, which bypasses the cap. Scenario paths are written
    # relative to the campaign file's directory (loader resolves them
    # from there).
    for k in steps:
        if k > total:
            print(f"  skip step {k}: exceeds generated total {total}")
            continue
        entries = "\n".join(
            f"  - scenarios/small-talk-{i:03d}.yaml" for i in range(1, k + 1)
        )
        camp = (
            f"# AUTO-GENERATED — load ramp step: {k} concurrent V2 calls.\n"
            f"# Run with the matching concurrency:\n"
            f"#   opkura campaign {out}/load-{k:03d}.yaml -m {k}\n"
            f"# Every entry is the same small-talk persona; {k} distinct\n"
            f"# files are required because the loader dedupes paths.\n\n"
            f'name: "Load Test · ramp {k}"\n'
            f"description: |\n"
            f"  {k} concurrent small-talk V2 calls against the target, for\n"
            f"  capacity testing. Generated by scripts/gen_loadtest.py.\n\n"
            f"# Capped at 50 in YAML; pass -m {k} on the CLI to actually run {k}.\n"
            f"max_concurrency: {min(k, 50)}\n\n"
            f"fail_fast: false\n\n"
            f"scenarios:\n{entries}\n"
        )
        cp = out / f"load-{k:03d}.yaml"
        cp.write_text(camp, encoding="utf-8")
        print(f"  campaign: {cp}  ({k} calls)")

    print("\nDone. Start small and ramp up:")
    for k in steps:
        if k <= total:
            print(f"  opkura campaign {out}/load-{k:03d}.yaml -m {k}")


if __name__ == "__main__":
    main()