#!/usr/bin/env python3
"""
Generate the SBI YONO tool-call load test: N copies of the multi-hop
(3x module_switch) scenario + the full-suite campaign that fires them
concurrently. N distinct files are needed because the campaign loader dedupes
scenario paths (the same file listed N times collapses to one call).

Usage (from repo root, opkura/):
    python scripts/gen_sbi_toolcall_loadtest.py        # default N=5
    python scripts/gen_sbi_toolcall_loadtest.py 20     # 20 concurrent copies

Then run (places REAL outbound calls to +918062123187):
    opkura campaign clients/sbi/yono-general/campaigns/full-suite.yaml -m 5
"""
import re
import sys
from pathlib import Path

N = int(sys.argv[1]) if len(sys.argv) > 1 else 5

BASE = Path("clients/sbi/yono-general")
SRC = BASE / "tool-multihop-routing.yaml"
SCEN_DIR = BASE / "load-test" / ".generated" / "scenarios"
CAMPAIGN = BASE / "campaigns" / "full-suite.yaml"


def stamp_name(text: str, tag: str) -> str:
    """Append a unique suffix to the scenario's `name:` so copies are
    distinguishable in logs/results (path is what the loader dedupes on)."""
    return re.sub(
        r'^name: "(.*)"$',
        lambda m: f'name: "{m.group(1)} · {tag}"',
        text,
        count=1,
        flags=re.M,
    )


def main() -> None:
    src = SRC.read_text()
    SCEN_DIR.mkdir(parents=True, exist_ok=True)

    # clear any previous generation so counts stay exact
    for old in SCEN_DIR.glob("multihop-*.yaml"):
        old.unlink()

    entries = []
    for i in range(1, N + 1):
        (SCEN_DIR / f"multihop-{i:03d}.yaml").write_text(stamp_name(src, f"run {i:03d}"))
        entries.append(f"  - ../load-test/.generated/scenarios/multihop-{i:03d}.yaml")

    campaign = f"""# =============================================================================
# AUTO-GENERATED by scripts/gen_sbi_toolcall_loadtest.py — DO NOT hand-edit.
# SBI · Sia · TOOL-CALL test — {N} concurrent copies of the 3x module_switch
# multi-hop scenario (credit card -> cheque book -> fixed deposit).
# {N} distinct files are used because the loader dedupes scenario paths.
#
# This exercises the streamed tool-call path (the json.loads accumulator fix) on
# the SBI YONO bot (Gemma/Modal) under concurrency. Bot under test: +918062123187.
# Every run places REAL outbound calls.
#   opkura campaign {CAMPAIGN} -m 1     # validate with one
#   opkura campaign {CAMPAIGN} -m {N}     # fire all {N} concurrently
#
# Change the count:  python scripts/gen_sbi_toolcall_loadtest.py <N>
# =============================================================================

name: "SBI · Sia · tool-call test ({N}x 3-hop module_switch)"
description: |
  {N} concurrent copies of the multi-hop tool-call scenario against the SBI YONO
  bot: each call forces three module_switch tool calls (credit card -> cheque
  book -> fixed deposit). Stresses the streamed tool-call path under concurrency.
  Read tool-call behaviour from each per-call evaluation.json / logs.

max_concurrency: {N}

fail_fast: false

scenarios:
{chr(10).join(entries)}
"""
    CAMPAIGN.write_text(campaign)
    print(f"Generated {N} scenario copies in {SCEN_DIR}")
    print(f"Campaign: {CAMPAIGN} (max_concurrency={N})")


if __name__ == "__main__":
    main()
