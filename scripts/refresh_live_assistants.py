#!/usr/bin/env python3
"""Regenerate `clients/live-assistants.yaml` — the customer-data guard's list.

WHAT THIS ANSWERS
    "Which assistants can look up a real customer?" — because a test that
    authenticates against a real account writes to the client's production CRM.
    Post-call processing runs after EVERY turn, and `is_test` suppresses only the
    compliance event.

WHY ACCOUNT COUNT AND NOT THE NAME
    "An `Imported - ` clone is a safe sandbox" is FALSE. Importing a bot copies
    its account table. Measured 2026-08-25 on US db 63:
        Imported - RSI_V3                       957,069 accounts
        Imported - Qwen Testing ACS 3P IB v2.0  431,712 accounts
    Believing the name is how a test run leaked into production.

HOW TO RUN IT
    There is no OSV API for this, so it reads the Orchestrator Service database
    through Metabase. Two ways:

    1. Ask Claude Code (or anyone with the region MCP servers configured) to run
       the SQL below against the right database and paste the rows in:
            US     Metabase db 63
            India  Metabase db 105
            Canada Metabase db 2   (verify)

    2. Any Metabase session token: set METABASE_URL and METABASE_API_KEY and run
       this script with --fetch.

    Then: python scripts/refresh_live_assistants.py --rows rows.txt --region us

THE SQL
    Keep this in sync with what the file claims. `clients` filter is optional —
    without it you get every assistant in the region (636 of 1,310 in the US had
    at least one account on 2026-08-25), which is a large but perfectly valid
    list.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import sys
from pathlib import Path

SQL = """
SELECT a.uuid::text || '|' || a.id || '|' || COUNT(acc.id) || '|' ||
       replace(c.name, '|', '/') || '|' || replace(a.name, '|', '/') AS line
FROM assistants a
JOIN clients c ON c.id = a.client_id
LEFT JOIN accounts acc ON acc.assistant_id = a.id
-- Optional narrowing to the clients opkura has scenarios for. Drop the WHERE to
-- cover the whole region.
WHERE c.name ILIKE ANY (ARRAY[
  '%veros%','%associated credit%','%pollack%','%penn%','%resurgent%','%midland%'
])
GROUP BY a.id, a.uuid, a.name, c.name
HAVING COUNT(acc.id) > 0
ORDER BY COUNT(acc.id) DESC;
""".strip()

HEADER = """# Assistants that hold real customer accounts — DO NOT point a test at these.
#
# GENERATED by scripts/refresh_live_assistants.py. Hand edits are overwritten on
# the next refresh — put manual entries under `extra:` at the bottom instead.
#
# The rule is the ACCOUNT COUNT, not the assistant's name: an `Imported - ` clone
# copies the account table and can carry hundreds of thousands of real customers.
#
# `is_test` does NOT make this safe. It suppresses only the compliance event;
# post-call processing runs after every turn and POSTs the caller's name, account
# number, SSN last-4, address and due amount to the client's real CRM.
#
# To use a listed assistant anyway, set `allow_customer_data: true` in the
# scenario and say in a comment why those accounts are not real customers.
#
# Assistants with zero accounts are deliberately absent — absence is what makes
# one usable for testing.
"""


def render(rows: list[str], region: str, source: str, today: str) -> str:
    out = [HEADER, f'generated_at: "{today}"', f"region: {region}",
           f'source: "{source}"', "", "assistants:"]
    seen: set[str] = set()
    for line in rows:
        line = line.strip()
        if not line:
            continue
        parts = line.split("|", 4)
        if len(parts) != 5:
            print(f"skipping unparseable row: {line!r}", file=sys.stderr)
            continue
        uuid, aid, count, client, name = (p.strip() for p in parts)
        if uuid in seen:
            continue
        seen.add(uuid)
        out += [
            f'  - uuid: "{uuid}"',
            f"    assistant_id: {aid}",
            f"    accounts: {count}",
            f'    client: "{client}"',
            f'    name: "{name}"',
        ]
    out += [
        "",
        "# Hand-maintained additions the query cannot know about — an assistant in a",
        "# region opkura cannot reach, or one a human knows is customer-facing despite",
        "# an empty account table. Same shape as above; survives a refresh.",
        "extra: []",
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--rows", type=Path,
                    help="file of 'uuid|id|accounts|client|name' lines from the SQL")
    ap.add_argument("--region", default="us", choices=("us", "in", "ca"))
    ap.add_argument("--out", type=Path,
                    default=Path(__file__).resolve().parents[1] / "clients" / "live-assistants.yaml")
    ap.add_argument("--print-sql", action="store_true", help="print the SQL and exit")
    args = ap.parse_args()

    if args.print_sql or not args.rows:
        print(SQL)
        if not args.print_sql:
            print("\n-- Run the above, save the rows to a file, then re-run with "
                  "--rows <file>", file=sys.stderr)
        return 0

    rows = args.rows.read_text(encoding="utf-8").splitlines()
    db = {"us": "db 63", "in": "db 105", "ca": "db 2"}[args.region]
    text = render(
        rows, args.region,
        f"{args.region.upper()} Orchestrator Service (Metabase {db})",
        _dt.date.today().isoformat(),
    )
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(rows)} row(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
