"""Which assistants hold real customer accounts.

The guard this backs exists because of a specific mistake: a text scenario was
pointed at Veros CI OB (assistant 1160, 13,399 accounts), authenticated, and the
post-call integration POSTed a real application number to the client's
production workflow API. Nothing in vjudge objected.

The tempting rule is "an `Imported - ` clone is a sandbox". It is false —
`Imported - RSI_V3` carries 957,069 accounts, because importing a bot copies its
account table. So the signal is the account count, which lives in
`clients/live-assistants.yaml` and is regenerated by
`scripts/refresh_live_assistants.py`.

Loaded lazily and cached: lint runs over a thousand scenarios in a loop and must
not re-read this file for each one.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import yaml

logger = logging.getLogger(__name__)

DEFAULT_PATH = Path(__file__).resolve().parents[2] / "clients" / "live-assistants.yaml"


@dataclass(frozen=True)
class LiveAssistant:
    uuid: str
    assistant_id: Optional[int]
    accounts: int
    client: str
    name: str

    def describe(self) -> str:
        return (
            f"assistant {self.assistant_id} {self.name!r} ({self.client}) — "
            f"{self.accounts:,} customer account(s)"
        )


_cache: Optional[dict[str, LiveAssistant]] = None
_cached_path: Optional[Path] = None


def _coerce(entry: dict) -> Optional[LiveAssistant]:
    uuid = entry.get("uuid")
    if not isinstance(uuid, str) or not uuid.strip():
        return None
    try:
        accounts = int(entry.get("accounts") or 0)
    except (TypeError, ValueError):
        accounts = 0
    raw_id = entry.get("assistant_id")
    return LiveAssistant(
        uuid=uuid.strip().lower(),
        assistant_id=int(raw_id) if isinstance(raw_id, int) else None,
        accounts=accounts,
        client=str(entry.get("client") or "unknown client"),
        name=str(entry.get("name") or "unnamed"),
    )


def load(path: Optional[Path] = None, *, refresh: bool = False) -> dict[str, LiveAssistant]:
    """uuid (lowercased) -> LiveAssistant. Missing file yields an empty map.

    A missing or unparseable file must never break linting: the guard is a
    safety net, and a broken net is still better than a crashed run — but it is
    logged, because silently guarding nothing is the worst outcome.
    """
    global _cache, _cached_path
    target = path or DEFAULT_PATH
    if not refresh and _cache is not None and _cached_path == target:
        return _cache

    entries: dict[str, LiveAssistant] = {}
    try:
        raw = yaml.safe_load(target.read_text(encoding="utf-8")) or {}
    except FileNotFoundError:
        logger.debug("no live-assistant list at %s — guard inactive", target)
        raw = {}
    except Exception as exc:
        logger.warning(
            "could not read the live-assistant list at %s (%s) — the guard "
            "against testing on customer data is INACTIVE for this run",
            target, exc,
        )
        raw = {}

    if isinstance(raw, dict):
        for key in ("assistants", "extra"):
            for entry in raw.get(key) or []:
                if isinstance(entry, dict):
                    live = _coerce(entry)
                    if live is not None:
                        entries[live.uuid] = live

    _cache, _cached_path = entries, target
    return entries


def lookup(assistant_uuid: str, path: Optional[Path] = None) -> Optional[LiveAssistant]:
    if not assistant_uuid or not isinstance(assistant_uuid, str):
        return None
    return load(path).get(assistant_uuid.strip().lower())
